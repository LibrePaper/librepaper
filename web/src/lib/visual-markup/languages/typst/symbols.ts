// Typst's sym and emoji namespaces: a dotted path after the namespace (dash.em, face.smile) to the
// character it inserts. Names outside these tables are not replaced; the layer shows their source.

type SymbolRow = [path: string, text: string];

function build(rows: SymbolRow[], label: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const [path, text] of rows) {
    if (map.has(path)) throw new Error(`Duplicate ${label} in the Typst symbol tables: ${path}`);
    map.set(path, text);
  }
  return map;
}

