import type { WidgetKind } from '../../core/language';

// How a command draws.
export type Render =
  | { kind: 'mark'; class: string }          // style the last mandatory argument with class
  | { kind: 'declaration'; class: string }   // style from after the command to the end of the enclosing group or environment
  | { kind: 'hide' }                          // draws nothing; hidden together with its arguments
  | { kind: 'symbol'; text: string }          // replaced by text; its arguments, if any, are hidden
  | { kind: 'chip'; text: string; block?: boolean; argument?: boolean } // placeholder for generated or opaque content; `argument` appends ': <first mandatory argument>'
  | { kind: 'widget'; widget: WidgetKind; block?: boolean }
  | { kind: 'source' };                       // recognized, shown as source

export interface CommandSpec { args: string; render: Render }
// args: xparse-style letters read left to right: 's' optional star, 'o' optional [..], 'm' mandatory {..}.

export type EnvironmentRender =
  | { kind: 'theorem'; title: string; numbered: boolean }  // header "Title N (optional name)."; numbered from document facts
  | { kind: 'proof' }                                       // header "Proof." (or the optional argument), ends with a QED mark
  | { kind: 'abstract' } | { kind: 'keywords' }             // header "Abstract" / "Keywords"
  | { kind: 'quote' }                                       // indented block
  | { kind: 'align'; align: 'center' | 'left' | 'right' }
  | { kind: 'code'; language?: string }                     // verbatim lexing: body is not parsed
  | { kind: 'opaque'; text: string }                        // whole environment folds into a block chip (e.g. "TikZ picture"); source on caret
  | { kind: 'bibliography' }                                // thebibliography, items via \bibitem
  | { kind: 'columns' } | { kind: 'box' }                   // multicols; minipage, framed boxes
  | { kind: 'plain' };                                      // body shown normally, delimiters collapse

export interface EnvironmentSpec { args: string; render: EnvironmentRender }

type CommandRow = [name: string, args: string, render: Render];
type EnvironmentRow = [name: string, args: string, render: EnvironmentRender];

const mark = (cls: string): Render => ({ kind: 'mark', class: cls });
const declaration = (cls: string): Render => ({ kind: 'declaration', class: cls });
const symbol = (text: string): Render => ({ kind: 'symbol', text });
const chip = (text: string, flags: { block?: boolean; argument?: boolean } = {}): Render => ({ kind: 'chip', text, ...flags });
const widget = (kind: WidgetKind, block = false): Render => (block ? { kind: 'widget', widget: kind, block } : { kind: 'widget', widget: kind });
const hide: Render = { kind: 'hide' };
const source: Render = { kind: 'source' };
const plain: EnvironmentRender = { kind: 'plain' };
const theorem = (title: string): EnvironmentRender => ({ kind: 'theorem', title, numbered: true });
const align = (position: 'center' | 'left' | 'right'): EnvironmentRender => ({ kind: 'align', align: position });

// Builds a map from rows, failing loudly if a name is listed twice (a later row would silently win).
function build<T>(rows: [string, T][], label: string): Map<string, T> {
  const map = new Map<string, T>();
  for (const [name, spec] of rows) {
    if (map.has(name)) throw new Error(`Duplicate ${label} in the LaTeX catalog: ${name}`);
    map.set(name, spec);
  }
  return map;
}

