import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import test from "node:test";
import { moduleSource } from "./calepin-runtime.mjs";

const files = [
  { path: ".calepin/calepin.typ", text: "#let document = none\n" },
  { path: ".calepin/runtime/a.typ", text: "// a \"quoted\" line\n" },
];

test("moduleSource starts with the generated-by comment and the version", () => {
  const source = moduleSource("0.0.60", files);
  assert.ok(
    source.startsWith("// Generated by web/tools/calepin-runtime.mjs from Calepin 0.0.60. Do not edit.\n"),
  );
  assert.match(source, /^\/\/ Calepin's Typst runtime \(MIT, by the same author\)/m);
});

test("moduleSource evaluates to the version and files it was given", async () => {
  const directory = await mkdtemp(join(tmpdir(), "calepin-runtime-test-"));
  try {
    const path = join(directory, "runtime.mjs");
    await writeFile(path, moduleSource("0.0.60", files));
    const module = await import(pathToFileURL(path).href);
    assert.equal(module.CALEPIN_VERSION, "0.0.60");
    assert.deepEqual(module.FILES, files);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

test("moduleSource ends with a newline", () => {
  assert.equal(moduleSource("0.0.60", files).endsWith("\n"), true);
  assert.equal(moduleSource("0.0.60", []).endsWith("\n"), true);
});
