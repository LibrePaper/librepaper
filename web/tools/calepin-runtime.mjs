#!/usr/bin/env node
// Regenerates web/src/lib/calepin-runtime.js from the `calepin` program on
// this computer. The browser bundles Calepin's Typst runtime so that a
// notebook that has never been run still compiles, with code shown and no
// output. Run it again after upgrading Calepin.

import { execFileSync } from "node:child_process";
import { mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const OUTPUT = fileURLToPath(new URL("../src/lib/calepin-runtime.js", import.meta.url));
const EMPTY = '#import "/.calepin/calepin.typ" as calepin\n#show: calepin.document\n';

// The text of the generated module. Pure, so the test can check it without
// Calepin installed.
export function moduleSource(version, files) {
  return [
    `// Generated by web/tools/calepin-runtime.mjs from Calepin ${version}. Do not edit.`,
    "// Calepin's Typst runtime (MIT, by the same author), bundled so that a notebook that has never been run still compiles in the browser.",
    `export const CALEPIN_VERSION = ${JSON.stringify(version)};`,
    `export const FILES = ${JSON.stringify(files, null, 1)};`,
    "",
  ].join("\n");
}

// Every file under `dir`, as paths relative to `root`, with forward slashes.
async function walk(root, dir) {
  const found = [];
  for (const entry of await readdir(join(root, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) found.push(...(await walk(root, path)));
    else found.push(path);
  }
  return found;
}

function calepinVersion() {
  const output = execFileSync("calepin", ["--version"], { encoding: "utf8" }).trim();
  const match = /\d+\.\d+\.\d+\S*/.exec(output);
  return match ? match[0] : output;
}

async function collect(root) {
  const paths = [".calepin/calepin.typ", ".calepin/syntax.tmTheme", ...(await walk(root, ".calepin/runtime"))];
  paths.sort();
  const files = [];
  for (const path of paths) {
    files.push({ path, text: await readFile(join(root, path), "utf8") });
  }
  return files;
}

async function main() {
  const version = calepinVersion();
  const root = await mkdtemp(join(tmpdir(), "calepin-runtime-"));
  try {
    await writeFile(join(root, "empty.typ"), EMPTY);
    execFileSync("calepin", ["compile", "empty.typ", "--format", "pdf"], { cwd: root, stdio: "inherit" });
    const files = await collect(root);
    await writeFile(OUTPUT, moduleSource(version, files));
    console.log(`Wrote ${files.length} runtime files from Calepin ${version} to ${OUTPUT}`);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
