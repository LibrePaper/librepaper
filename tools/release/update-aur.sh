#!/usr/bin/env bash
set -euo pipefail

: "${AUR_SSH_PRIVATE_KEY:?AUR_SSH_PRIVATE_KEY is required}"
source "$(dirname "${BASH_SOURCE[0]}")/release-updater-common.sh"

tag="$(release_updater_validate_tag "${LIBREPAPER_RELEASE_TAG:-${GITHUB_REF_NAME:-}}")"

version="${tag#v}"
deb="librepaper_${version}_amd64.deb"
tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

actual="$(release_updater_fetch_verified_asset "${tag}" "${deb}" "${tmpdir}")"

# Keep the AUR key in a private file that only git uses.
key_file="${tmpdir}/aur-key"
known_hosts="${tmpdir}/known_hosts"
printf '%s\n' "${AUR_SSH_PRIVATE_KEY}" > "${key_file}"
chmod 600 "${key_file}"
export GIT_SSH_COMMAND="ssh -i ${key_file} -o IdentitiesOnly=yes -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=${known_hosts}"

# Cloning a package that does not exist yet gives an empty repository.
aur_dir="${tmpdir}/librepaper-bin"
git clone ssh://aur@aur.archlinux.org/librepaper-bin.git "${aur_dir}"
cd "${aur_dir}"

cat > PKGBUILD <<PKGBUILD
# Maintainer: Vincent Arel-Bundock <vincent@arelbundock.com>
# This file is generated by LibrePaper's release workflow. DO NOT EDIT.
pkgname=librepaper-bin
pkgver=${version}
pkgrel=1
pkgdesc="LibrePaper desktop app, with the librepaper command line"
arch=('x86_64')
url="https://librepaper.org"
license=('MIT')
depends=('webkit2gtk-4.1' 'gtk3')
provides=('librepaper')
conflicts=('librepaper')
source=("https://github.com/LibrePaper/librepaper/releases/download/v\${pkgver}/librepaper_\${pkgver}_amd64.deb"
        "LICENSE-\${pkgver}::https://raw.githubusercontent.com/LibrePaper/librepaper/v\${pkgver}/LICENSE")
sha256sums=('${actual}'
            'SKIP')
package() {
  bsdtar -xf data.tar.gz -C "\$pkgdir"
  install -Dm644 "LICENSE-\${pkgver}" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
PKGBUILD

# makepkg is not available on the runner, so .SRCINFO is written by hand.
# Each key in the pkgbase block starts with a tab.
indent=$'\t'
cat > .SRCINFO <<SRCINFO
pkgbase = librepaper-bin
${indent}pkgdesc = LibrePaper desktop app, with the librepaper command line
${indent}pkgver = ${version}
${indent}pkgrel = 1
${indent}url = https://librepaper.org
${indent}arch = x86_64
${indent}license = MIT
${indent}depends = webkit2gtk-4.1
${indent}depends = gtk3
${indent}provides = librepaper
${indent}conflicts = librepaper
${indent}source = https://github.com/LibrePaper/librepaper/releases/download/v${version}/${deb}
${indent}source = LICENSE-${version}::https://raw.githubusercontent.com/LibrePaper/librepaper/v${version}/LICENSE
${indent}sha256sums = ${actual}
${indent}sha256sums = SKIP

pkgname = librepaper-bin
SRCINFO

# Stage .SRCINFO first so both files land in one commit.
git add .SRCINFO
release_updater_publish_file PKGBUILD \
  "AUR package already up to date" "Update to ${version}" master
